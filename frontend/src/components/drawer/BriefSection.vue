<script setup lang="ts">
import { ExternalLinkIcon, SparklesIcon } from '@lucide/vue'
import { computed } from 'vue'

import { ApiError } from '@/api/client'
import { Button } from '@/components/ui/button'
import { useLoadWhenSettled } from '@/composables/useLoadWhenSettled'
import { useBriefStore } from '@/stores/briefs'

const props = defineProps<{ ticker: string }>()

const store = useBriefStore()
const entry = computed(() => store.entryFor(props.ticker))
const brief = computed(() => entry.value?.data ?? null)

const state = computed<'loading' | 'not-found' | 'unavailable' | 'ready'>(() => {
  const current = entry.value
  if (current?.data) return 'ready'
  if (current?.error instanceof ApiError && current.error.status === 404) return 'not-found'
  if (current?.error) return 'unavailable'
  return 'loading' // writing, or still waiting for the drawer to settle on this ticker
})

/** "gemini-3.8-flash" → "Gemini 3.8 Flash", for the disclaimer. */
function modelLabel(model: string): string {
  return model
    .split('-')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ')
}

// Gemini's free tier is small: only the ticker the drawer settles on gets a brief
useLoadWhenSettled(() => props.ticker, store.load)
</script>

<template>
  <!-- AI text is only ever interpolated ({{ }} escapes it), never rendered as HTML -->
  <section aria-labelledby="brief-heading" class="flex flex-col gap-3">
    <h3 id="brief-heading" class="text-sm font-medium">AI brief</h3>

    <template v-if="state === 'ready' && brief">
      <div>
        <h4 class="text-xs font-medium text-muted-foreground">About</h4>
        <p class="mt-1 text-sm">{{ brief.about }}</p>
      </div>

      <div>
        <h4 class="text-xs font-medium text-muted-foreground">In the news</h4>
        <ul v-if="brief.news.length" class="mt-1 list-disc space-y-1 pl-4 text-sm">
          <li v-for="(point, index) in brief.news" :key="index">{{ point }}</li>
        </ul>
        <p v-else class="mt-1 text-sm text-muted-foreground">No business news this week.</p>
      </div>

      <div v-if="brief.sources.length">
        <h4 class="text-xs font-medium text-muted-foreground">Sources</h4>
        <ul class="mt-1 space-y-1 text-sm">
          <li v-for="source in brief.sources" :key="source.url">
            <a
              :href="source.url"
              target="_blank"
              rel="noopener noreferrer"
              class="inline-flex items-start gap-1 hover:underline"
            >
              <span>
                <span class="text-muted-foreground">{{ source.source }} ·</span>
                {{ source.headline }}
              </span>
              <ExternalLinkIcon class="mt-0.5 size-3.5 shrink-0" aria-hidden="true" />
            </a>
          </li>
        </ul>
      </div>

      <p class="flex gap-1.5 text-xs text-muted-foreground">
        <SparklesIcon class="mt-0.5 size-3.5 shrink-0" aria-hidden="true" />
        <span>
          AI-generated by {{ modelLabel(brief.model) }} from this week's headlines. It can be wrong,
          so check the sources. Not financial advice.
        </span>
      </p>
    </template>
    <p v-else-if="state === 'not-found'" class="text-sm text-muted-foreground">
      No brief for this ticker.
    </p>
    <div v-else-if="state === 'unavailable'" class="flex items-center justify-between text-sm">
      <span class="text-muted-foreground">The AI brief is unavailable right now.</span>
      <Button variant="outline" size="sm" @click="store.load(ticker)">Retry</Button>
    </div>
    <div v-else class="space-y-2" aria-busy="true" aria-label="Loading the AI brief">
      <p class="text-xs text-muted-foreground">Writing a brief from this week's news…</p>
      <div v-for="bar in 4" :key="bar" class="h-5 animate-pulse rounded bg-muted" />
    </div>
  </section>
</template>
