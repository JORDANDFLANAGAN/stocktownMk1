import { fireEvent, render, screen } from '@testing-library/vue'
import { createPinia } from 'pinia'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

import { ApiError, type Api, type Brief } from '@/api/client'
import { fakeApi } from '@/__tests__/fakeApi'
import { TEST_BRIEF } from '@/__tests__/fixtures'
import { API_KEY } from '@/composables/useApi'
import { SETTLE_MS } from '@/composables/useLoadWhenSettled'
import BriefSection from '../BriefSection.vue'

/** An Api that records each ticker it is asked to brief and answers with `answer`. */
function recordingApi(answer: (ticker: string) => Promise<Brief>) {
  const briefedTickers: string[] = []
  const api = fakeApi({
    fetchBrief: (ticker) => {
      briefedTickers.push(ticker)
      return answer(ticker)
    },
  })
  return { api, briefedTickers }
}

async function renderSettled(api: Api) {
  render(BriefSection, {
    props: { ticker: 'AAA' },
    global: { plugins: [createPinia()], provide: { [API_KEY]: api } },
  })
  await vi.advanceTimersByTimeAsync(SETTLE_MS)
}

describe('BriefSection', () => {
  beforeEach(() => vi.useFakeTimers())
  afterEach(() => vi.useRealTimers())

  it('waits for the drawer to settle before asking for a brief', async () => {
    const { api, briefedTickers } = recordingApi(async () => TEST_BRIEF)
    render(BriefSection, {
      props: { ticker: 'AAA' },
      global: { plugins: [createPinia()], provide: { [API_KEY]: api } },
    })

    await vi.advanceTimersByTimeAsync(SETTLE_MS - 1)
    expect(briefedTickers).toEqual([])

    await vi.advanceTimersByTimeAsync(1)
    expect(briefedTickers).toEqual(['AAA'])
  })

  it('shows the about text, news points, linked sources and the AI disclaimer naming the model', async () => {
    await renderSettled(recordingApi(async () => TEST_BRIEF).api)

    expect(screen.getByText(TEST_BRIEF.about)).toBeTruthy()
    expect(screen.getAllByRole('listitem').map((item) => item.textContent?.trim())).toContain(
      'Alpha Corp opened a new widget plant.',
    )
    const source = screen.getByRole('link', { name: /Alpha Corp Names New CEO/ })
    expect(source.getAttribute('href')).toBe('https://example.com/alpha-ceo')
    expect(source.getAttribute('target')).toBe('_blank')
    expect(source.getAttribute('rel')).toBe('noopener noreferrer')
    expect(screen.getByText(/AI-generated by Gemini 3\.8 Flash/).textContent).toMatch(
      /It can be\s+wrong.*Not financial advice\./s,
    )
  })

  it('says there was no business news this week, and lists no sources', async () => {
    const quietWeek: Brief = { ...TEST_BRIEF, news: [], sources: [] }

    await renderSettled(recordingApi(async () => quietWeek).api)

    expect(screen.getByText('No business news this week.')).toBeTruthy()
    expect(screen.queryByText('Sources')).toBeNull()
    expect(screen.queryAllByRole('link')).toEqual([])
    expect(screen.getByText(/AI-generated by/)).toBeTruthy()
  })

  it('offers a retry when the brief is unavailable, and the retry asks again', async () => {
    let attempts = 0
    const { api, briefedTickers } = recordingApi(async () => {
      attempts += 1
      if (attempts === 1) throw new ApiError(503, 60)
      return TEST_BRIEF
    })
    await renderSettled(api)

    expect(screen.getByText('The AI brief is unavailable right now.')).toBeTruthy()
    await fireEvent.click(screen.getByRole('button', { name: 'Retry' }))

    expect(await screen.findByText(TEST_BRIEF.about)).toBeTruthy()
    expect(briefedTickers).toEqual(['AAA', 'AAA'])
  })

  it('shows AI text as text, never as HTML', async () => {
    const injected = '<img src="x" onerror="alert(1)"> Alpha Corp makes widgets.'

    await renderSettled(recordingApi(async () => ({ ...TEST_BRIEF, about: injected })).api)

    expect(screen.getByText(injected)).toBeTruthy()
    expect(document.querySelector('img')).toBeNull()
  })
})
